"""
Usage example for Token2Wav.

Assumes you have a CosyVoice3 pretrained model directory, e.g.:
    pretrained_models/CosyVoice3-0.5B/
        ├── flow.pt
        └── hift.pt

Inputs (all from CosyVoice3 frontend / LLM):
    token        : [1, N]    int32   - speech tokens generated by LLM
    prompt_token : [1, M]    int32   - speech tokens of the reference audio (from speech tokenizer)
    prompt_feat  : [1, T, 80] float  - mel spectrogram of the reference audio
    embedding    : [1, 192]   float  - speaker embedding (from CAM++ model)

Output:
    tts_speech   : [1, S]    float   - waveform at 24kHz
"""

from omegaconf import DictConfig
import torch
import torchaudio

from .frontend import Token2WavFrontEnd
from .model import Token2Wav
from .flow.flow import CausalMaskedDiffWithDiT
from .flow.flow_matching import CausalConditionalCFM
from .flow.DiT.dit import DiT
from .hifigan.generator import CausalHiFTGenerator
from .hifigan.f0_predictor import CausalConvRNNF0Predictor
from .transformer.upsample_encoder import PreLookaheadLayer


def build_flow_hift(fp16=False):
    """Build flow + hift from scratch, matching CosyVoice3 config."""

    flow = CausalMaskedDiffWithDiT(
        input_size=80,
        output_size=80,
        spk_embed_dim=192,
        output_type='mel',
        vocab_size=6561,
        input_frame_rate=25,
        only_mask_loss=True,
        token_mel_ratio=2,
        pre_lookahead_len=3,
        pre_lookahead_layer=PreLookaheadLayer(
            in_channels=80,
            channels=1024,
            pre_lookahead_len=3,
        ),
        decoder=CausalConditionalCFM(
            in_channels=240,
            n_spks=1,
            spk_emb_dim=80,
            cfm_params=DictConfig({
                'sigma_min': 1e-06,
                'solver': 'euler',
                't_scheduler': 'cosine',
                'training_cfg_rate': 0.2,
                'inference_cfg_rate': 0.7,
                'reg_loss_type': 'l1',
            }),
            estimator=DiT(
                dim=1024,
                depth=22,
                heads=16,
                dim_head=64,
                ff_mult=2,
                mel_dim=80,
                mu_dim=80,
                spk_dim=80,
                out_channels=80,
                static_chunk_size=50,   # 25 * 2
                num_decoding_left_chunks=-1,
            ),
        ),
    )

    hift = CausalHiFTGenerator(
        in_channels=80,
        base_channels=512,
        nb_harmonics=8,
        sampling_rate=24000,
        nsf_alpha=0.1,
        nsf_sigma=0.003,
        nsf_voiced_threshold=10,
        upsample_rates=[8, 5, 3],
        upsample_kernel_sizes=[16, 11, 7],
        istft_params={"n_fft": 16, "hop_len": 4},
        resblock_kernel_sizes=[3, 7, 11],
        resblock_dilation_sizes=[[1, 3, 5], [1, 3, 5], [1, 3, 5]],
        source_resblock_kernel_sizes=[7, 7, 11],
        source_resblock_dilation_sizes=[[1, 3, 5], [1, 3, 5], [1, 3, 5]],
        lrelu_slope=0.1,
        audio_limit=0.99,
        conv_pre_look_right=4,
        f0_predictor=CausalConvRNNF0Predictor(
            num_class=1,
            in_channels=80,
            cond_channels=512,
        ),
    )

    return Token2Wav(flow=flow, hift=hift, fp16=fp16)

def build_frontend(campplus_model, speech_tokenizer_model):
    return Token2WavFrontEnd(
        campplus_model=campplus_model,
        speech_tokenizer_model=speech_tokenizer_model,
    )

def build_model(flow_model, hift_model, campplus_model, speech_tokenizer_model, fp16=False, device=None):
    flow_hift = build_flow_hift(fp16=fp16)
    flow_hift.load(flow_model=flow_model, hift_model=hift_model)
    if device is not None:
        flow_hift.to(device)
    frontend = build_frontend(campplus_model, speech_tokenizer_model)
    return flow_hift, frontend

def prepare_prompt_conditioning(frontend, audio_path):
    orig_speech, orig_sr = torchaudio.load(audio_path)
    if orig_sr != 16000:
        speech_16k = torchaudio.transforms.Resample(orig_freq=orig_sr, new_freq=16000)(orig_speech)
    else:
        speech_16k = orig_speech

    if orig_sr != 24000:
        speech_24k = torchaudio.transforms.Resample(orig_freq=orig_sr, new_freq=24000)(orig_speech)
    else:
        speech_24k = orig_speech

    speaker_embedding = frontend.extract_speaker_embedding(speech_16k)
    prompt_speech_token, prompt_speech_token_len = frontend.extract_semantic_tokens(speech_16k)
    prompt_mel_features, prompt_mel_features_len = frontend.extract_mel_features(speech_24k)

    # 16K <-> 24K alignment
    token_len = min(int(prompt_mel_features.shape[1] / 2), prompt_speech_token.shape[1])
    prompt_mel_features, prompt_mel_features_len[:] = prompt_mel_features[:, :2 * token_len], 2 * token_len
    prompt_speech_token, prompt_speech_token_len[:] = prompt_speech_token[:, :token_len], token_len

    return speaker_embedding, prompt_speech_token, prompt_mel_features

def token2wav(model, token, prompt_conditioning=None,
              n_timesteps=10, cfg=True,
              prompt_token_emb=None, embedding_proj=None):
    speaker_embedding, prompt_speech_token, prompt_mel_features = prompt_conditioning

    tts_speech = model.token2wav(
        token=token,
        prompt_token=prompt_speech_token,
        prompt_feat=prompt_mel_features,
        embedding=speaker_embedding,
        speed=1.0,
        n_timesteps=n_timesteps,
        cfg=cfg,
        prompt_token_emb=prompt_token_emb,
        embedding_proj=embedding_proj,
    )
    return tts_speech
